function platformCard(c: {
  id: string;
  platform: "google_ads" | "tiktok";
  category: string;
  sector?: Sector;
  riskLevel?: RiskLevel;
  title: string;
  description: string;
  riskyExamples: string[];
  matchPatterns: string[];
  safeFix: string;
  source: { org: string; title: string; url: string };
  reference: string;
}): RuleCardDef {
  return {
    id: c.id,
    domain: "meta_policy",
    platform: c.platform,
    category: c.category,
    sector: c.sector ?? "genel",
    version: 1,
    status: "requires_review",
    riskLevel: c.riskLevel ?? "medium",
    title: c.title,
    description: c.description,
    riskyExamples: c.riskyExamples,
    matchPatterns: c.matchPatterns,
    safeReplacements: [],
    safeFix: c.safeFix,
    sourceOrg: c.source.org,
    sourceTitle: c.source.title,
    sourceUrl: c.source.url,
    sourceReference: c.reference,
    lastVerifiedAt: ADDED_ON,
    verificationNote: PLATFORM_NOT_READ,
    legalReviewStatus: "pending",
  };
}

