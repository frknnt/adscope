/**
 * Generates supabase/seed.sql from src/lib/rules/catalog.ts (single source of truth).
 * Run: npm run gen:seed
 */
import { writeFileSync } from "node:fs";
import { RULE_CATALOG } from "../src/lib/rules/catalog";
import { rulePlatform } from "../src/lib/platforms";

const q = (v: string | null | undefined) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a: string[]) => (a.length ? `array[${a.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

const lines: string[] = [
  "-- GENERATED by scripts/generate-seed.ts from src/lib/rules/catalog.ts. Do not edit by hand.",
  "-- Rule statuses: active = verified on an official source page; requires_review = not verified (info only);",
  "-- draft = never used by the engine.",
  "",
];
for (const r of RULE_CATALOG) {
  // A newer version (after expert review) replaces the older ones: retire them first so the
  // "one active version per card" index holds and the engine never sees two versions.
  if (r.version > 1)
    lines.push(`update public.rule_versions set status = 'retired' where rule_card_id = ${q(r.id)} and version < ${r.version} and status <> 'retired';`);
  lines.push(
    `insert into public.rule_cards (id, domain, category, sector, platform) values (${q(r.id)}, ${q(r.domain)}, ${q(r.category)}, ${q(r.sector)}, ${q(rulePlatform(r))})`,
    `  on conflict (id) do update set domain = excluded.domain, category = excluded.category, sector = excluded.sector, platform = excluded.platform;`,
  );
  lines.push(
    `insert into public.rule_versions (rule_card_id, version, status, risk_level, title, description, risky_examples, match_patterns, safe_replacements, flag_trigger, safe_fix, source_org, source_title, source_url, source_reference, effective_date, last_verified_at, verification_note, legal_review_status) values (` +
      [
        q(r.id), String(r.version), q(r.status), q(r.riskLevel), q(r.title), q(r.description),
        arr(r.riskyExamples), arr(r.matchPatterns), json(r.safeReplacements), q(r.flagTrigger ?? null), q(r.safeFix),
        q(r.sourceOrg), q(r.sourceTitle), q(r.sourceUrl), q(r.sourceReference ?? null),
        r.effectiveDate ? `${q(r.effectiveDate)}::date` : "null",
        r.lastVerifiedAt ? `${q(r.lastVerifiedAt)}::date` : "null",
        q(r.verificationNote), q(r.legalReviewStatus),
      ].join(", ") +
      `)`,
    `  on conflict (rule_card_id, version) do nothing;`,
    "",
  );
}
writeFileSync("supabase/seed.sql", lines.join("\n") + "\n");
console.log(`seed.sql written with ${RULE_CATALOG.length} rule cards`);
